export function seedTiles(): { tile: Tile; data: TileData }[] {
  return specs.map(([id, title, subtitle, type, icon, x, y, w, h, value, unit, state]) => {
    const numeric = typeof value === 'number';
    const limits = id === 'errors' ? [5, 10] : id === 'queue' ? [5, 20] : [60, 80];
    const rules =
      numeric && ['cpu', 'memory', 'errors', 'queue'].includes(id)
        ? [
            {
              id: 'critique',
              state: 'critical',
              enter: { operator: 'gte', value: limits[1] },
              exit: { operator: 'lt', value: limits[1] - 3 },
              holdSeconds: 0,
            },
            {
              id: 'attention',
              state: 'warning',
              enter: { operator: 'gte', value: limits[0] },
              exit: { operator: 'lt', value: limits[0] - 3 },
              holdSeconds: 0,
            },
          ]
        : [];
    return {
      tile: tileSchema.parse({
        id,
        layout: { x, y, w, h },
        content: { title, subtitle, type, icon, unit },
        thresholds: {
          staleAfterSeconds: 120,
          defaultState: state === 'info' ? 'info' : 'ok',
          rules,
        },
        demo: true,
      }),
      data: { value, status: 'up', message: id === 'deploy' ? 'v1.24.0 · il y a 4 minutes' : '' },
    };
  });
}
